#ifndef SOURCES_INC_COMMON_MATH_H_
#define SOURCES_INC_COMMON_MATH_H_

static inline int MATH_Min(int a, int b)
{
	return (a < b) ? a : b;
}

static inline int MATH_Max(int a, int b)
{
	return (a > b) ? a : b;
}

#endif /* SOURCES_INC_COMMON_MATH_H_ */
